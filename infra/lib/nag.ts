import type { Stack } from "aws-cdk-lib";
import { NagSuppressions, type NagPackSuppression } from "cdk-nag";
import type { IConstruct } from "constructs";

// Every cdk-nag suppression lives here with its reason (spec 03 req 9.2). Each one is
// scoped to the construct that triggers it (and its children), and wildcard findings
// are narrowed with `appliesTo` so a new, unexpected wildcard still fails synth.

function suppress(scope: IConstruct, rules: NagPackSuppression[]): void {
  NagSuppressions.addResourceSuppressions(scope, rules, true);
}

const regex = (source: string) => ({ regex: `/${source}/g` });

const NO_ACCESS_LOGS: NagPackSuppression = {
  id: "AwsSolutions-S1",
  reason:
    "Demo scope and cost: server access logs are not needed; API access logs cover requests.",
};

const BASIC_EXECUTION_ROLE: NagPackSuppression = {
  id: "AwsSolutions-IAM4",
  reason: "AWSLambdaBasicExecutionRole only grants writing to CloudWatch Logs.",
  appliesTo: [
    regex("^Policy::arn:(<AWS::Partition>|aws):iam::aws:policy\\/service-role\\/AWSLambdaBasicExecutionRole$"),
  ],
};

export interface AppStackNagTargets {
  readonly httpApi: IConstruct;
  readonly distribution: IConstruct;
  readonly buckets: readonly IConstruct[];
  readonly functions: readonly IConstruct[];
}

export function suppressAppStackFindings(stack: Stack, t: AppStackNagTargets): void {
  suppress(t.httpApi, [
    {
      id: "AwsSolutions-APIG4",
      reason:
        "Single-workspace demo without users by product decision; stage throttling and the budget bound abuse.",
    },
  ]);
  suppress(t.distribution, [
    { id: "AwsSolutions-CFR1", reason: "Public demo: no geo restriction by product decision." },
    {
      id: "AwsSolutions-CFR2",
      reason:
        "Public demo: WAF cost not justified; API throttling and the budget alarm are the guardrails.",
    },
    { id: "AwsSolutions-CFR3", reason: "Demo scope and cost: distribution access logs are not needed." },
    {
      id: "AwsSolutions-CFR4",
      reason:
        "The default *.cloudfront.net certificate fixes the viewer security policy (CDK ignores minimumProtocolVersion without a certificate); TLS 1.2 minimum arrives with a custom domain (spec 03 requirement 6.4).",
    },
  ]);
  for (const bucket of t.buckets) suppress(bucket, [NO_ACCESS_LOGS]);
  for (const fn of t.functions) {
    suppress(fn, [
      BASIC_EXECUTION_ROLE,
      {
        id: "AwsSolutions-IAM5",
        reason:
          "Object wildcards are the exact prefixes of security.md; the foundation-model region wildcard is required by cross-region inference profiles.",
        appliesTo: [
          regex("^Resource::<Media[A-Za-z0-9]+\\.Arn>\\/(tmp|media\\/products)\\/\\*$"),
          regex("^Resource::arn:aws:bedrock:\\*::foundation-model\\/[a-z0-9.:-]+$"),
        ],
      },
      {
        id: "AwsSolutions-L1",
        reason:
          "Runtime pinned to nodejs22.x by spec 03 and .nvmrc; moving to a newer runtime is a reviewed change.",
      },
    ]);
  }
  // CDK-managed helpers (BucketDeployment, autoDeleteObjects) whose code and policies
  // aws-cdk-lib owns; they are stack-level singletons named Custom::*.
  for (const helper of stack.node.children.filter((c) => c.node.id.startsWith("Custom::"))) {
    suppress(helper, [
      BASIC_EXECUTION_ROLE,
      {
        id: "AwsSolutions-IAM5",
        reason:
          "CDK-managed helper needs object-level wildcards on the buckets it manages; BucketDeployment's cloudfront:CreateInvalidation is granted on * by aws-cdk-lib.",
        appliesTo: [
          regex("^Action::s3:(GetObject|GetBucket|List|DeleteObject|Abort)\\*$"),
          regex("^Resource::<Frontend[A-Za-z0-9]+\\.Arn>\\/\\*$"),
          regex("^Resource::\\*$"),
          regex("^Resource::arn:(<AWS::Partition>|aws):s3:::cdk-[a-z0-9]+-assets-.+\\/\\*$"),
        ],
      },
      {
        id: "AwsSolutions-L1",
        reason: "CDK-managed helper Lambda; its runtime is controlled by aws-cdk-lib.",
      },
    ]);
  }
}

export function suppressPipelineStackFindings(stack: Stack, pipeline: IConstruct): void {
  suppress(pipeline, [
    {
      id: "AwsSolutions-CB4",
      reason:
        "Single-account pipeline without cross-account keys; artifacts use S3-managed encryption, avoiding a KMS key cost.",
    },
    {
      id: "AwsSolutions-IAM5",
      reason:
        "Roles generated by CDK Pipelines; wildcards are scoped to its artifacts bucket, its CodeBuild logs and reports, and the CDK bootstrap roles.",
      appliesTo: [
        regex("^Action::s3:(GetObject|GetBucket|List|DeleteObject|Abort)\\*$"),
        regex("^Resource::<PipelineArtifactsBucket[A-Za-z0-9]+\\.Arn>\\/\\*$"),
        regex(
          "^Resource::arn:(<AWS::Partition>|aws):(logs|codebuild):[a-z0-9-]+:[0-9]+:(log-group:\\/aws\\/codebuild\\/|report-group\\/).*\\*$",
        ),
        regex("^Resource::arn:\\*:iam::[0-9]+:role\\/\\*$"),
        // Teardown step (ADR 0014): the app stack id suffix is unknown before deploy.
        regex("^Resource::arn:(<AWS::Partition>|aws):cloudformation:[a-z0-9-]+:[0-9]+:stack\\/Prod-GhostStockAppStack\\/\\*$"),
      ],
    },
    NO_ACCESS_LOGS,
  ]);
  // `*` resources only on the two CDK-generated roles that need them, so a `*` added
  // anywhere else in the pipeline still fails synth.
  for (const path of [
    "Pipeline/Assets/FileRole/DefaultPolicy/Resource",
    "Pipeline/UpdatePipeline/SelfMutation/Role/DefaultPolicy/Resource",
  ]) {
    NagSuppressions.addResourceSuppressionsByPath(stack, `/${stack.stackName}/${path}`, [
      {
        id: "AwsSolutions-IAM5",
        reason:
          "CDK Pipelines grants codebuild:StartBuild/BatchGetBuilds/StopBuild (assets) and cloudformation:DescribeStacks, s3:ListBucket (self-mutation) on *.",
        appliesTo: [regex("^Resource::\\*$")],
      },
    ]);
  }
}
